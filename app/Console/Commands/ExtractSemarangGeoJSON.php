<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;

class ExtractSemarangGeoJSON extends Command
{
    /*
    |--------------------------------------------------------------------------
    | NAMA COMMAND ARTISAN
    |--------------------------------------------------------------------------
    */
    protected $signature = 'geojson:semarang';

    /*
    |--------------------------------------------------------------------------
    | DESKRIPSI COMMAND
    |--------------------------------------------------------------------------
    */
    protected $description = 'Extract GeoJSON Semarang';

    /*
    |--------------------------------------------------------------------------
    | PROSES UTAMA COMMAND
    |--------------------------------------------------------------------------
    */
    public function handle()
    {
        /*
        |--------------------------------------------------------------------------
        | LOKASI FILE GEOJSON SUMBER
        |--------------------------------------------------------------------------
        */
        $path = storage_path(
            'app/geojson/indonesia_villages_border.geojson'
        );

        /*
        |--------------------------------------------------------------------------
        | MEMBACA DAN MENGUBAH FILE JSON
        |--------------------------------------------------------------------------
        */
        $json = json_decode(file_get_contents($path), true);

        /*
        |--------------------------------------------------------------------------
        | MENYIAPKAN STRUKTUR HASIL FILTER
        |--------------------------------------------------------------------------
        */
        $filtered = [
            'type' => 'FeatureCollection',
            'features' => []
        ];

        /*
        |--------------------------------------------------------------------------
        | FILTER DATA WILAYAH SEMARANG
        |--------------------------------------------------------------------------
        */
        foreach ($json['features'] as $feature) {

            /*
            |--------------------------------------------------------------------------
            | MENGAMBIL INFORMASI FEATURE
            |--------------------------------------------------------------------------
            */
            $properties = $feature['properties'];

            /*
            |--------------------------------------------------------------------------
            | MENGUBAH PROPERTIES MENJADI TEKS
            |--------------------------------------------------------------------------
            */
            $text = json_encode($properties);

            /*
            |--------------------------------------------------------------------------
            | MENGECEK DATA SEMARANG
            |--------------------------------------------------------------------------
            */
            if (
                str_contains(
                    strtolower($text),
                    'semarang'
                )
            ) {
                $filtered['features'][] = $feature;
            }
        }

        /*
        |--------------------------------------------------------------------------
        | LOKASI FILE HASIL
        |--------------------------------------------------------------------------
        */
        $output =
            public_path(
                'data/kabupaten/semarang.geojson'
            );

        /*
        |--------------------------------------------------------------------------
        | MENYIMPAN FILE GEOJSON
        |--------------------------------------------------------------------------
        */
        file_put_contents(
            $output,
            json_encode($filtered)
        );

        /*
        |--------------------------------------------------------------------------
        | MENAMPILKAN PESAN BERHASIL
        |--------------------------------------------------------------------------
        */
        $this->info(
            '✅ GeoJSON Semarang berhasil dibuat!'
        );
    }
}